def spatial_temporal_match(
    target,
    source,
    prefix,
    max_days=3,
    max_distance_deg=0.5
):

    target = target.copy()
    source = source.copy()

    # Make sure dates are datetime
    target["Date"] = pd.to_datetime(
        target["Date"],
        errors="coerce"
    )

    source["Date"] = pd.to_datetime(
        source["Date"],
        errors="coerce"
    )

    # Remove invalid data
    source = source.dropna(
        subset=["Date", "Latitude", "Longitude"]
    )

    target = target.dropna(
        subset=["Date", "Latitude", "Longitude"]
    )

    # Create spatial tree
    source_coords = source[
        ["Latitude", "Longitude"]
    ].values

    tree = cKDTree(source_coords)

    target_coords = target[
        ["Latitude", "Longitude"]
    ].values

    distances, indices = tree.query(
        target_coords,
        distance_upper_bound=max_distance_deg
    )

    # Prepare result
    result = target.copy()

    # Source matched rows
    matched = pd.DataFrame(
        index=result.index
    )

    valid = indices < len(source)

    matched.loc[valid, :] = source.iloc[
        indices[valid]
    ].values

    # Match source date
    source_dates = pd.Series(
        pd.NaT,
        index=result.index,
        dtype="datetime64[ns]"
    )

    source_dates.loc[valid] = source.iloc[
        indices[valid]
    ]["Date"].values

    # Temporal difference
    time_difference = (
        result["Date"].values
        - source_dates.values
    )

    time_difference_days = (
        np.abs(
            time_difference
            / np.timedelta64(1, "D")
        )
    )

    # Final valid match
    final_valid = (
        valid &
        (time_difference_days <= max_days)
    )

    # Add source variables
    source_variables = [
        c for c in source.columns
        if c not in [
            "Date",
            "Latitude",
            "Longitude"
        ]
    ]

    for col in source_variables:

        new_col = prefix + "_" + col

        values = np.full(
            len(result),
            np.nan
        )

        source_values = source.iloc[
            indices[final_valid]
        ][col].values

        values[final_valid] = source_values

        result[new_col] = values

    result[prefix + "_Distance"] = np.where(
        final_valid,
        distances,
        np.nan
    )

    result[prefix + "_TimeDiffDays"] = np.where(
        final_valid,
        time_difference_days,
        np.nan
    )

    return result

